LARGURA, ALTURA = 5, 7
FONTE = {c: [linha for linha in g.split()] for c, g in _GLIFOS.items()}


def largura_texto(texto: str, escala: int, espaco: int = 1) -> int:
    return len(texto) * (LARGURA + espaco) * escala - espaco * escala


def desenhar(pixel, texto: str, x: int, y: int, escala: int, cor, espaco: int = 1) -> None:
    """Chama pixel(x, y, cor) para cada ponto do texto, com canto superior em (x, y)."""
    cursor = x
    for char in texto.upper():
        glifo = FONTE.get(char)
        if glifo is not None:
            for linha_idx, linha in enumerate(glifo):
                for col_idx, bit in enumerate(linha):
                    if bit == "1":
                        for dy in range(escala):
                            for dx in range(escala):
                                pixel(cursor + col_idx * escala + dx, y + linha_idx * escala + dy, cor)
        cursor += (LARGURA + espaco) * escala
